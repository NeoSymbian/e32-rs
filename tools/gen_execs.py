"""gen_execs.py -- generate crates/e32-sys/src/execs.rs from the kernel's execs.txt.

Numbers the executive calls the way kernel/eka/kernel/genexec.pl does: fast and slow calls are two separate lists in
file order; a call with an explicit non-zero `number` keeps it, every other call takes the next free number. Fast
call numbers carry EXECUTIVE_FAST (0x00800000), the bit the kernel reads from the `swi` immediate.

Usage: gen_execs.py <path/to/execs.txt> [out.rs]   (default out: crates/e32-sys/src/execs.rs)
"""
import os
import re
import sys

EXECUTIVE_FAST = 0x00800000


def parse(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)  # execs.txt goes through cpp in genexec.pl
    text = re.sub(r"//[^\n]*", "", text)
    lists = {"fast": [], "slow": []}
    for kind, body in re.findall(r"\b(fast|slow)\s*\{(.*?)\}", text, flags=re.S):
        x = {"args": []}
        for line in body.splitlines():
            m = re.match(r"\s*(\w+)\s*(?:=\s*(.*?))?\s*$", line)
            if not m:
                continue
            key, val = m.group(1), m.group(2)
            if key == "name":
                x["name"] = val
            elif key == "number":
                x["number"] = int(val, 0)
            elif re.fullmatch(r"arg\d", key):
                x["args"].append(val)
            elif key == "return":
                x["ret"] = val
        if "name" not in x:
            sys.exit(f"unnamed {kind} exec")
        lists[kind].append(x)
    for xs in lists.values():
        taken = {x["number"] for x in xs if x.get("number")}
        nxt = 0
        for x in xs:
            if not x.get("number"):
                while nxt in taken:
                    nxt += 1
                x["number"] = nxt
                nxt += 1
    return lists


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.upper()


def render(lists):
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// GENERATED by tools/gen_execs.py from kernel/eka/kernel/execs.txt -- do not edit.",
           "//! Executive call numbers: the `swi` immediate for each call (fast ones include `EXECUTIVE_FAST`).",
           "", "/// The bit the kernel reads from the `swi` immediate to tell a fast executive call from a slow one.",
           f"pub const EXECUTIVE_FAST: u32 = 0x{EXECUTIVE_FAST:08x};", ""]
    for kind in ("fast", "slow"):
        xs = sorted(lists[kind], key=lambda x: x["number"])
        out.append(f"/// {kind.capitalize()} executive calls ({len(xs)}).")
        out.append(f"pub mod {kind} {{")
        for x in xs:
            sig = ", ".join(x["args"]) or "-"
            out.append(f"    /// `{x['name']}({sig}) -> {x.get('ret', 'TInt')}`")
            val = x["number"] | (EXECUTIVE_FAST if kind == "fast" else 0)
            out.append(f"    pub const {snake(x['name'])}: u32 = 0x{val:08x};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "crates", "e32-sys", "src", "execs.rs")
    lists = parse(open(src).read())
    num = {(k, x["name"]): x["number"] for k, xs in lists.items() for x in xs}
    # self-check against the official genexec.pl output (exec_enum.h of the 2010 release)
    assert num[("fast", "WaitForAnyRequest")] == 0
    assert num[("slow", "ObjectNext")] == 0
    assert num[("slow", "DebugPrint")] == 86, num[("slow", "DebugPrint")]
    assert num[("slow", "ThreadKill")] == 115, num[("slow", "ThreadKill")]
    assert num[("slow", "UserThreadExiting")] == 246, num[("slow", "UserThreadExiting")]
    assert (len(lists["fast"]), len(lists["slow"])) == (44, 271), (len(lists["fast"]), len(lists["slow"]))
    for k, xs in lists.items():
        assert len({snake(x["name"]) for x in xs}) == len(xs), f"duplicate const name in {k}"
    with open(dst, "w") as fh:
        fh.write(render(lists).rstrip("\n") + "\n")  # exactly what rustfmt keeps
    print(f"{dst}: {len(lists['fast'])} fast, {len(lists['slow'])} slow")


if __name__ == "__main__":
    main()
